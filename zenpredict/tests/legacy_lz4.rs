//! Frozen ZNPR v3 bake made with the canonical baker and lz4_flex 0.11.6.
//! The model is identity(2*x0 - x1 + 0.5), with identity input scaling.
//! Keep the bytes frozen: a round trip through today's encoder cannot prove
//! that files produced before a compression-library upgrade still load.

